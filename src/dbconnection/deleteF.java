    private void loadEventDataIntoTable() {
    try {
        
        String sql = "SELECT * FROM EVENT";
        PreparedStatement stmt = conn.prepareStatement(sql);
        ResultSet rs = stmt.executeQuery();

       
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); 

        while (rs.next()) {
            int eventId = rs.getInt("EventID");
            String title = rs.getString("Title");
            String description = rs.getString("Description");
            Date startDate = rs.getDate("Start_Date");
            Date endDate = rs.getDate("End_Date");
            int teamId = rs.getInt("TeamID");
            int clientId = rs.getInt("ClientID");
            int venueId = rs.getInt("VenueID");

     
            model.addRow(new Object[]{eventId, title, description, startDate, endDate, teamId, clientId, venueId});
        }

        rs.close();
        stmt.close();
       

    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error loading event data: " + ex.getMessage());
    }
}

