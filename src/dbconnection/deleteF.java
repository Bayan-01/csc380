    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String eventIDStr = jTextField1.getText().trim();

        if (eventIDStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the Event ID.");
            return;
        }

        try {
            int eventID = Integer.parseInt(eventIDStr);

            String sql = "DELETE FROM EVENT WHERE EventID = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setInt(1, eventID);

            int rows = pstmt.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this, "Event deleted successfully.");
                loadEventDataIntoTable();
            } else {
                JOptionPane.showMessageDialog(this, "No event found with that ID.");
            }

            pstmt.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for Event ID.");
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButton2ActionPerformed

