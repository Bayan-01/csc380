    private void enteridActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enteridActionPerformed
      
   int attendeeId;
    try {
        attendeeId = Integer.parseInt(idtxt.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid numeric Attendee ID.",
            "Input Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    DefaultTableModel model = (DefaultTableModel) displayTable.getModel();
    model.setRowCount(0);
    String sql =
        "SELECT t.Tier, " 
      + "       t.TicketID, "
      + "       e.Title, "
      + "       e.Start_Date, "
      + "       v.Name, "
      + "       v.Location "
      + "  FROM Ticket t "
      + "  JOIN Event  e ON t.EventID = e.EventID "
      + "  JOIN Venue  v ON e.VenueID = v.VenueID "
      + " WHERE t.AttendeeID = ?";

    try (PreparedStatement ps = conn.prepareStatement(sql)) {
        ps.setInt(1, attendeeId);

        try (ResultSet rs = ps.executeQuery()) {
            boolean found = false;
            while (rs.next()) {
                found = true;
                Object[] row = {
                    rs.getString("Tier"),
                    rs.getInt   ("TicketID"),
                    rs.getString("Title"),
                    rs.getDate  ("Start_Date"),
                    rs.getString("Name"),
                    rs.getString("Location")
                };
                model.addRow(row);
            }
            if (!found) {
                JOptionPane.showMessageDialog(
                    this,
                    "No tickets found for Attendee ID " + attendeeId + ".",
                    "No Data",
                    JOptionPane.INFORMATION_MESSAGE
                );
            }
        }
    } catch (SQLException ex) {
        Logger.getLogger(ViewTix.class.getName())
              .log(Level.SEVERE, "Error loading tickets for ID=" + attendeeId, ex);
        JOptionPane.showMessageDialog(
            this,
            "An error occurred while retrieving data. Please try again later.",
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_enteridActionPerformed

