    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {

            String sql = "INSERT INTO EVENT (Title, Description, Start_Date, End_Date, TeamID, ClientID, VenueID) " +
            "VALUES (?, ?, ?, ?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);

            String title= jTextField6.getText();
            String description = jTextField8.getText();
            String  startDate = jTextField7.getText();
            String  endDate = jTextField5.getText();
            int  eventID = Integer.parseInt(jTextField2.getText());
            int teamID = Integer.parseInt(jTextField3.getText());
            int clientID = Integer.parseInt(jTextField1.getText());
            int venueID = Integer.parseInt(jTextField4.getText());

            pstmt.setString(1, title);
            pstmt.setString(2, description);
            pstmt.setDate(3, java.sql.Date.valueOf(startDate));
            pstmt.setDate(4, java.sql.Date.valueOf(endDate));
            pstmt.setInt(5, teamID);
            pstmt.setInt(6, clientID);
            pstmt.setInt(7, venueID);

            int rowsInserted = pstmt.executeUpdate();

            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Event added successfully!");
                loadEventData();
            }

            pstmt.close();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for IDs and dates.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
        catch (SQLException sqlEx) {

            JOptionPane.showMessageDialog(this, "Database error: " + sqlEx.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "An error occurred while inserting data:\n" + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

