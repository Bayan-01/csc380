     private void updateEventRowInTable(int eventId) {
    try {
        
        
        String sql = "SELECT * FROM EVENT WHERE EventID = ?";
        PreparedStatement stmt = conn.prepareStatement(sql);
        stmt.setInt(1, eventId);
        ResultSet rs = stmt.executeQuery();

        if (rs.next()) {
          
            String title = rs.getString("Title");
            String description = rs.getString("Description");
            Date startDate = rs.getDate("Start_Date");
            Date endDate = rs.getDate("End_Date");
            int teamId = rs.getInt("TeamID");
            int clientId = rs.getInt("ClientID");
            int venueId = rs.getInt("VenueID");

           
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            for (int i = 0; i < model.getRowCount(); i++) {
                if ((int) model.getValueAt(i, 0) == eventId) { 
                    model.setValueAt(title, i, 1);
                    model.setValueAt(description, i, 2);
                    model.setValueAt(startDate, i, 3);
                    model.setValueAt(endDate, i, 4);
                    model.setValueAt(teamId, i, 5);
                    model.setValueAt(clientId, i, 6);
                    model.setValueAt(venueId, i, 7);
                    break;
                }
            }
        }

        rs.close();
        stmt.close();
       

    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error updating row in table: " + ex.getMessage());
    }
}

