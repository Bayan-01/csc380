    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

  
    String eventIdStr = jTextField3.getText().trim();
    String newEndDateStr = jTextField4.getText().trim(); 

    if (eventIdStr.isEmpty() || newEndDateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in both Event ID and new End Date.");
        return;
    }

    try {
        int eventId = Integer.parseInt(eventIdStr);


        java.sql.Date newEndDate = java.sql.Date.valueOf(newEndDateStr); 

        

        String sql = "UPDATE EVENT SET End_Date = ? WHERE EventID = ?";
        PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setDate(1, newEndDate);
        pstmt.setInt(2, eventId);

        int rowsUpdated = pstmt.executeUpdate();

        if (rowsUpdated > 0) {
            JOptionPane.showMessageDialog(this, "End date updated successfully.");
           updateEventRowInTable(eventId); 
        } else {
            JOptionPane.showMessageDialog(this, "No event found with that ID.");
        }

        pstmt.close();
        

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid Event ID.");
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, "Invalid date format. Use yyyy-MM-dd.");
    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
    }







    }//GEN-LAST:event_jButton2ActionPerformed

