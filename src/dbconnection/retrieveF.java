    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String eventIdStr = jTextField1.getText().trim();

        if (eventIdStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter an Event ID.");
            return;
        }

        try {
            int eventId = Integer.parseInt(eventIdStr);

            String sql = "SELECT * FROM EVENT WHERE EventID = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setInt(1, eventId);
            ResultSet rs = pstmt.executeQuery();

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            if (rs.next()) {
                Object[] row = {
                    rs.getInt("EventID"),
                    rs.getString("Title"),
                    rs.getString("Description"),
                    rs.getDate("Start_Date"),
                    rs.getDate("End_Date"),
                    rs.getInt("TeamID"),
                    rs.getInt("ClientID"),
                    rs.getInt("VenueID")
                };
                model.addRow(row);
            } else {
                JOptionPane.showMessageDialog(this, "No event found with this ID.");
            }

            rs.close();
            pstmt.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid Event ID. Please enter a number.");
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButton1ActionPerformed

